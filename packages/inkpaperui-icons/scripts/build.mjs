import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ICONS } from '../icons.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const isCheck = process.argv.includes('--check');

const svg = (body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;

/** Only what a data URL can't carry raw, so the CSS stays readable and diffable. */
const dataUrl = (markup) => `url("data:image/svg+xml,${markup.replace(/"/g, "'").replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E')}")`;

const names = Object.keys(ICONS).sort();
const css =
  '/* Generated by scripts/build.mjs from icons.mjs; edit the icons there. */\n' +
  '@layer utilities {\n' +
  names.map((name) => `  .ip-i-${name} {\n    --ip-icon: ${dataUrl(svg(ICONS[name]))};\n  }\n`).join('\n') +
  '}\n';

const outputs = {
  'src/index.css': css,
  'icons.json': `${JSON.stringify(names, null, 2)}\n`,
  ...Object.fromEntries(names.map((name) => [`svg/${name}.svg`, `${svg(ICONS[name]).replace('stroke="#000"', 'stroke="currentColor"')}\n`])),
};

const stale = [];
for (const [path, contents] of Object.entries(outputs)) {
  const file = join(root, path);
  if (isCheck) {
    let current = '';
    try {
      current = readFileSync(file, 'utf8');
    } catch {}
    if (current !== contents) stale.push(path);
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, contents);
  }
}

/** A renamed or removed icon would otherwise leave its old SVG behind for anyone copying files. */
const svgDir = join(root, 'svg');
for (const file of readdirSync(svgDir)) {
  if (outputs[`svg/${file}`] !== undefined) continue;
  if (isCheck) stale.push(`svg/${file} (no such icon)`);
  else rmSync(join(svgDir, file));
}

if (stale.length > 0) {
  console.error(`Out of date, run npm run build: ${stale.join(', ')}`);
  process.exit(1);
}
console.log(isCheck ? `${names.length} icons up to date.` : `Built ${names.length} icons.`);
